                    <li>Gerenciar perfis e permissões;</li>
                    <li>Possibilitar publicações e interações;</li>
                    <li>Organizar eventos, projetos e tarefas;</li>
                    <li>Registrar participações e resultados de votações;</li>
                    <li>Enviar notificações relacionadas à plataforma;</li>
                    <li>Realizar a recuperação de senhas;</li>
                    <li>Auxiliar na segurança, no monitoramento e na auditoria das atividades.</li>
                </ul>
            </section>

