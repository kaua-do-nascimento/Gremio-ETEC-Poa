            <section>
                <h2>1. APRESENTAÇÃO</h2>

                <p>
                    Esta Política de Privacidade explica como o Sistema de Gestão de Grêmio Estudantil coleta, utiliza, armazena e protege as informações dos usuários.
                </p>

                <p>
                    A plataforma foi desenvolvida para centralizar a comunicação escolar e facilitar a interação entre os estudantes e o Grêmio Estudantil da ETEC de Poá.
                </p>

                <p>
                    O tratamento de dados pessoais deverá observar a Lei Geral de Proteção de Dados Pessoais (Lei nº 13.709/2018 — LGPD).
                </p>
            </section>

            <section>
                <h2>2. DADOS COLETADOS</h2>

                <p>
                    Durante a utilização da plataforma, poderão ser coletadas e armazenadas as seguintes informações:
                </p>

                <p><strong>Dados de cadastro e identificação:</strong></p>

                <ul>
                    <li>Nome completo;</li>
                    <li>Registro de Matrícula (RM);</li>
                    <li>E-mail;</li>
                    <li>Senha armazenada em formato de hash;</li>
                    <li>Foto de perfil.</li>
                </ul>

                <p><strong>Dados de utilização:</strong></p>

                <ul>
                    <li>Publicações realizadas;</li>
                    <li>Interações e reações;</li>
                    <li>Participações e votos em votações;</li>
                    <li>Participação em eventos;</li>
                    <li>Informações relacionadas a projetos e tarefas;</li>
                    <li>Preferências e configurações da conta;</li>
                    <li>Notificações recebidas.</li>
                </ul>

                <p><strong>Dados técnicos e de segurança:</strong></p>

                <ul>
                    <li>Endereço IP;</li>
                    <li>Navegador e informações do dispositivo (user agent);</li>
                    <li>Registros de login;</li>
                    <li>Data e horário de determinadas atividades;</li>
                    <li>Registros de alterações realizadas no sistema.</li>
                </ul>

                <p>
                    Essas informações estão relacionadas às estruturas e funcionalidades documentadas no banco de dados do projeto.
                </p>
            </section>

